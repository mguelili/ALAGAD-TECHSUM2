<h1>About the System</h1>

<p>
    The Tasks for Today Management System is a CodeIgniter 4 application
    that helps a team monitor daily and upcoming tasks.
</p>

<p>
    The Welcome page displays tasks scheduled for the current date,
    while the Task List page displays every task stored in the MySQL database.
</p>

